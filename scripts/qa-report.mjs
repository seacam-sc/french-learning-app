// Writes content/QA_REPORT.md: counts by status, level, format; flags; validator result.
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { checkQuestions } from './validate-questions.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const load = (d) => !existsSync(join(root, d)) ? [] : readdirSync(join(root, d)).filter((f) => f.endsWith('.json')).flatMap((f) => JSON.parse(readFileSync(join(root, d, f))));
const qs = [...load('content/candidates'), ...load('content/questions')];
const objectives = JSON.parse(readFileSync(join(root, 'curriculum/objectives.json')));
const { errors, warnings } = checkQuestions(qs, objectives);
const tally = (key) => qs.reduce((m, q) => ((m[q[key]] = (m[q[key]] || 0) + 1), m), {});
const table = (obj) => ['| | Count |', '|---|---|', ...Object.entries(obj).sort().map(([k, v]) => `| ${k} | ${v} |`)].join('\n');
const flagged = qs.filter((q) => q.flags?.length);
const objCovered = new Set(qs.map((q) => q.objective_id)).size;
const md = `# Question QA report

Generated by \`npm run qa\` on ${new Date().toISOString().slice(0, 10)}. Numbers come from the data files.

**${qs.length} questions** across ${objCovered} of ${objectives.length} objectives.
Validator: ${errors.length} error(s), ${warnings.length} warning(s).

No question below is independently linguistically verified unless its status is \`approved\`. \`ai_reviewed\` means one AI model checked another AI model's work.

## By status
${table(tally('status'))}

## By level
${table(tally('level'))}

## By format
${table(tally('format'))}

## Flagged questions (${flagged.length})
${flagged.map((q) => `- **${q.id}** (${q.status}): ${q.flags.join('; ')}`).join('\n') || 'None.'}

## Validator warnings
${warnings.map((w) => `- ${w}`).join('\n') || 'None.'}
${errors.length ? '\n## Validator errors\n' + errors.map((e) => `- ${e}`).join('\n') : ''}
`;
writeFileSync(join(root, 'content/QA_REPORT.md'), md);
console.log(`Wrote content/QA_REPORT.md (${qs.length} questions, ${flagged.length} flagged)`);
